-- 12. VISTAS PARA REPORTES
-- ============================================================

CREATE OR REPLACE VIEW VW_PRODUCTOS_BAJO_INVENTARIO AS
SELECT ID_PRODUCTO,CODIGO,NOMBRE,TIPO_PRODUCTO,EXISTENCIA,ACTIVO
FROM PRODUCTO
WHERE EXISTENCIA <= 5;

CREATE OR REPLACE VIEW VW_PUNTOS_CLIENTES AS
SELECT ID_CLIENTE,IDENTIFICACION,NOMBRE,PUNTOS,ACTIVO
FROM CLIENTE;

CREATE OR REPLACE VIEW VW_MENU_COMPLETO AS
SELECT
    m.ID_MENU,
    m.CODIGO,
    m.NOMBRE AS MENU,
    m.PRECIO,
    s.NOMBRE AS SANDWICH,
    b.NOMBRE AS BEBIDA,
    a.NOMBRE AS ACOMPANAMIENTO,
    m.ACTIVO
FROM MENU_COMPLETO m
JOIN PRODUCTO s ON s.ID_PRODUCTO=m.ID_SANDWICH
JOIN PRODUCTO b ON b.ID_PRODUCTO=m.ID_BEBIDA
JOIN PRODUCTO a ON a.ID_PRODUCTO=m.ID_ACOMPANAMIENTO;

COMMIT;

