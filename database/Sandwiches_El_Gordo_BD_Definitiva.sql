CREATE TABLE CATEGORIA (
    ID_CATEGORIA NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOMBRE VARCHAR2(50) NOT NULL UNIQUE,
    DESCRIPCION VARCHAR2(250),
    ACTIVO CHAR(1) DEFAULT 'S' NOT NULL,
    CONSTRAINT CK_CATEGORIA_ACTIVO CHECK (ACTIVO IN ('S','N'))
);

CREATE TABLE CLIENTE (
    ID_CLIENTE NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    IDENTIFICACION VARCHAR2(25) NOT NULL UNIQUE,
    NOMBRE VARCHAR2(120) NOT NULL,
    TELEFONO VARCHAR2(25),
    CORREO VARCHAR2(120),
    DIRECCION VARCHAR2(250),
    PUNTOS NUMBER DEFAULT 0 NOT NULL,
    ACTIVO CHAR(1) DEFAULT 'S' NOT NULL,
    FECHA_REGISTRO DATE DEFAULT SYSDATE NOT NULL,
    CONSTRAINT CK_CLIENTE_PUNTOS CHECK (PUNTOS >= 0),
    CONSTRAINT CK_CLIENTE_ACTIVO CHECK (ACTIVO IN ('S','N'))
);

CREATE TABLE PRODUCTO (
    ID_PRODUCTO NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CODIGO VARCHAR2(20) NOT NULL UNIQUE,
    NOMBRE VARCHAR2(100) NOT NULL,
    DESCRIPCION VARCHAR2(300),
    TIPO_PRODUCTO VARCHAR2(20) NOT NULL,
    MARCA VARCHAR2(80),
    PRECIO NUMBER(10,2) NOT NULL,
    EXISTENCIA NUMBER DEFAULT 0 NOT NULL,
    ID_CATEGORIA NUMBER NOT NULL,
    ACTIVO CHAR(1) DEFAULT 'S' NOT NULL,
    CONSTRAINT FK_PRODUCTO_CATEGORIA
        FOREIGN KEY (ID_CATEGORIA) REFERENCES CATEGORIA(ID_CATEGORIA),
    CONSTRAINT CK_PRODUCTO_TIPO
        CHECK (TIPO_PRODUCTO IN ('SANDWICH','BEBIDA','ACOMPANAMIENTO')),
    CONSTRAINT CK_PRODUCTO_PRECIO CHECK (PRECIO >= 0),
    CONSTRAINT CK_PRODUCTO_EXISTENCIA CHECK (EXISTENCIA >= 0),
    CONSTRAINT CK_PRODUCTO_ACTIVO CHECK (ACTIVO IN ('S','N'))
);

-- Un menu no tiene existencia propia:
-- consume 1 sandwich + 1 bebida + 1 acompanamiento.
CREATE TABLE MENU_COMPLETO (
    ID_MENU NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CODIGO VARCHAR2(20) NOT NULL UNIQUE,
    NOMBRE VARCHAR2(100) NOT NULL,
    DESCRIPCION VARCHAR2(300),
    PRECIO NUMBER(10,2) NOT NULL,
    ID_SANDWICH NUMBER NOT NULL,
    ID_BEBIDA NUMBER NOT NULL,
    ID_ACOMPANAMIENTO NUMBER NOT NULL,
    ACTIVO CHAR(1) DEFAULT 'S' NOT NULL,
    CONSTRAINT FK_MENU_SANDWICH
        FOREIGN KEY (ID_SANDWICH) REFERENCES PRODUCTO(ID_PRODUCTO),
    CONSTRAINT FK_MENU_BEBIDA
        FOREIGN KEY (ID_BEBIDA) REFERENCES PRODUCTO(ID_PRODUCTO),
    CONSTRAINT FK_MENU_ACOMP
        FOREIGN KEY (ID_ACOMPANAMIENTO) REFERENCES PRODUCTO(ID_PRODUCTO),
    CONSTRAINT CK_MENU_PRECIO CHECK (PRECIO >= 0),
    CONSTRAINT CK_MENU_ACTIVO CHECK (ACTIVO IN ('S','N'))
);

-- ============================================================
-- 2. PEDIDOS Y PAGOS
-- ============================================================

CREATE TABLE PEDIDO (
    ID_PEDIDO NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_CLIENTE NUMBER NOT NULL,
    FECHA_CREACION DATE DEFAULT SYSDATE NOT NULL,
    SUBTOTAL NUMBER(10,2) DEFAULT 0 NOT NULL,
    DESCUENTO NUMBER(10,2) DEFAULT 0 NOT NULL,
    TOTAL NUMBER(10,2) DEFAULT 0 NOT NULL,
    PUNTOS_GENERADOS NUMBER DEFAULT 0 NOT NULL,
    ESTADO VARCHAR2(15) DEFAULT 'PENDIENTE' NOT NULL,
    CONSTRAINT FK_PEDIDO_CLIENTE
        FOREIGN KEY (ID_CLIENTE) REFERENCES CLIENTE(ID_CLIENTE),
    CONSTRAINT CK_PEDIDO_SUBTOTAL CHECK (SUBTOTAL >= 0),
    CONSTRAINT CK_PEDIDO_DESCUENTO CHECK (DESCUENTO >= 0),
    CONSTRAINT CK_PEDIDO_TOTAL CHECK (TOTAL >= 0),
    CONSTRAINT CK_PEDIDO_PUNTOS CHECK (PUNTOS_GENERADOS >= 0),
    CONSTRAINT CK_PEDIDO_ESTADO
        CHECK (ESTADO IN ('PENDIENTE','PAGADO','ENTREGADO','ANULADO'))
);

CREATE TABLE DETALLE_PEDIDO (
    ID_DETALLE NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_PEDIDO NUMBER NOT NULL,
    TIPO_ITEM VARCHAR2(15) NOT NULL,
    ID_PRODUCTO NUMBER,
    ID_MENU NUMBER,
    CANTIDAD NUMBER NOT NULL,
    PRECIO_UNITARIO NUMBER(10,2) NOT NULL,
    SUBTOTAL NUMBER(10,2) NOT NULL,
    PUNTOS NUMBER DEFAULT 0 NOT NULL,
    CONSTRAINT FK_DETALLE_PEDIDO
        FOREIGN KEY (ID_PEDIDO) REFERENCES PEDIDO(ID_PEDIDO),
    CONSTRAINT FK_DETALLE_PRODUCTO
        FOREIGN KEY (ID_PRODUCTO) REFERENCES PRODUCTO(ID_PRODUCTO),
    CONSTRAINT FK_DETALLE_MENU
        FOREIGN KEY (ID_MENU) REFERENCES MENU_COMPLETO(ID_MENU),
    CONSTRAINT CK_DETALLE_TIPO CHECK (TIPO_ITEM IN ('PRODUCTO','MENU')),
    CONSTRAINT CK_DETALLE_CANTIDAD CHECK (CANTIDAD > 0),
    CONSTRAINT CK_DETALLE_PRECIO CHECK (PRECIO_UNITARIO >= 0),
    CONSTRAINT CK_DETALLE_SUBTOTAL CHECK (SUBTOTAL >= 0),
    CONSTRAINT CK_DETALLE_PUNTOS CHECK (PUNTOS >= 0),
    CONSTRAINT CK_DETALLE_ITEM CHECK (
        (TIPO_ITEM = 'PRODUCTO' AND ID_PRODUCTO IS NOT NULL AND ID_MENU IS NULL)
        OR
        (TIPO_ITEM = 'MENU' AND ID_MENU IS NOT NULL AND ID_PRODUCTO IS NULL)
    )
);

CREATE TABLE PAGO (
    ID_PAGO NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_PEDIDO NUMBER NOT NULL UNIQUE,
    FECHA_PAGO DATE DEFAULT SYSDATE NOT NULL,
    METODO VARCHAR2(10) NOT NULL,
    MONTO NUMBER(10,2) NOT NULL,
    DINERO_RECIBIDO NUMBER(10,2),
    CAMBIO NUMBER(10,2),
    REFERENCIA VARCHAR2(100),
    ESTADO VARCHAR2(15) DEFAULT 'APROBADO' NOT NULL,
    CONSTRAINT FK_PAGO_PEDIDO
        FOREIGN KEY (ID_PEDIDO) REFERENCES PEDIDO(ID_PEDIDO),
    CONSTRAINT CK_PAGO_METODO CHECK (METODO IN ('EFECTIVO','TARJETA')),
    CONSTRAINT CK_PAGO_MONTO CHECK (MONTO >= 0),
    CONSTRAINT CK_PAGO_RECIBIDO CHECK
        (DINERO_RECIBIDO IS NULL OR DINERO_RECIBIDO >= 0),
    CONSTRAINT CK_PAGO_CAMBIO CHECK (CAMBIO IS NULL OR CAMBIO >= 0),
    CONSTRAINT CK_PAGO_ESTADO CHECK (ESTADO IN ('APROBADO','RECHAZADO'))
);

-- ============================================================
-- 3. INVENTARIO
-- ============================================================

CREATE TABLE MOVIMIENTO_INVENTARIO (
    ID_MOVIMIENTO NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_PRODUCTO NUMBER NOT NULL,
    FECHA DATE DEFAULT SYSDATE NOT NULL,
    TIPO_MOVIMIENTO VARCHAR2(20) NOT NULL,
    CANTIDAD NUMBER NOT NULL,
    EXISTENCIA_ANTERIOR NUMBER,
    EXISTENCIA_NUEVA NUMBER,
    REFERENCIA VARCHAR2(100),
    CONSTRAINT FK_MOVINV_PRODUCTO
        FOREIGN KEY (ID_PRODUCTO) REFERENCES PRODUCTO(ID_PRODUCTO),
    CONSTRAINT CK_MOVINV_TIPO CHECK (
        TIPO_MOVIMIENTO IN ('ABASTECIMIENTO','VENTA','CANJE','AJUSTE')
    ),
    CONSTRAINT CK_MOVINV_CANTIDAD CHECK (CANTIDAD > 0),
    CONSTRAINT CK_MOVINV_ANT CHECK
        (EXISTENCIA_ANTERIOR IS NULL OR EXISTENCIA_ANTERIOR >= 0),
    CONSTRAINT CK_MOVINV_NUEVA CHECK
        (EXISTENCIA_NUEVA IS NULL OR EXISTENCIA_NUEVA >= 0)
);

-- ============================================================
-- 4. FIDELIZACION Y CANJES
-- ============================================================

CREATE TABLE RECOMPENSA (
    ID_RECOMPENSA NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOMBRE VARCHAR2(100) NOT NULL,
    DESCRIPCION VARCHAR2(300),
    PUNTOS_NECESARIOS NUMBER NOT NULL,
    ID_PRODUCTO NUMBER,
    ID_MENU NUMBER,
    ACTIVO CHAR(1) DEFAULT 'S' NOT NULL,
    CONSTRAINT FK_RECOMPENSA_PRODUCTO
        FOREIGN KEY (ID_PRODUCTO) REFERENCES PRODUCTO(ID_PRODUCTO),
    CONSTRAINT FK_RECOMPENSA_MENU
        FOREIGN KEY (ID_MENU) REFERENCES MENU_COMPLETO(ID_MENU),
    CONSTRAINT CK_RECOMPENSA_PUNTOS CHECK (PUNTOS_NECESARIOS > 0),
    CONSTRAINT CK_RECOMPENSA_ACTIVO CHECK (ACTIVO IN ('S','N')),
    CONSTRAINT CK_RECOMPENSA_ITEM CHECK (
        (ID_PRODUCTO IS NOT NULL AND ID_MENU IS NULL)
        OR
        (ID_MENU IS NOT NULL AND ID_PRODUCTO IS NULL)
    )
);

CREATE TABLE CANJE (
    ID_CANJE NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_CLIENTE NUMBER NOT NULL,
    ID_RECOMPENSA NUMBER NOT NULL,
    FECHA DATE DEFAULT SYSDATE NOT NULL,
    PUNTOS_UTILIZADOS NUMBER NOT NULL,
    ESTADO VARCHAR2(15) DEFAULT 'APROBADO' NOT NULL,
    CONSTRAINT FK_CANJE_CLIENTE
        FOREIGN KEY (ID_CLIENTE) REFERENCES CLIENTE(ID_CLIENTE),
    CONSTRAINT FK_CANJE_RECOMPENSA
        FOREIGN KEY (ID_RECOMPENSA) REFERENCES RECOMPENSA(ID_RECOMPENSA),
    CONSTRAINT CK_CANJE_PUNTOS CHECK (PUNTOS_UTILIZADOS > 0),
    CONSTRAINT CK_CANJE_ESTADO CHECK (ESTADO IN ('APROBADO','RECHAZADO'))
);

CREATE TABLE MOVIMIENTO_PUNTOS (
    ID_MOVIMIENTO NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_CLIENTE NUMBER NOT NULL,
    FECHA DATE DEFAULT SYSDATE NOT NULL,
    TIPO_MOVIMIENTO VARCHAR2(15) NOT NULL,
    PUNTOS NUMBER NOT NULL,
    ID_PEDIDO NUMBER,
    ID_CANJE NUMBER,
    REFERENCIA VARCHAR2(150),
    CONSTRAINT FK_MOVPUNTOS_CLIENTE
        FOREIGN KEY (ID_CLIENTE) REFERENCES CLIENTE(ID_CLIENTE),
    CONSTRAINT FK_MOVPUNTOS_PEDIDO
        FOREIGN KEY (ID_PEDIDO) REFERENCES PEDIDO(ID_PEDIDO),
    CONSTRAINT FK_MOVPUNTOS_CANJE
        FOREIGN KEY (ID_CANJE) REFERENCES CANJE(ID_CANJE),
    CONSTRAINT CK_MOVPUNTOS_TIPO
        CHECK (TIPO_MOVIMIENTO IN ('ACUMULACION','CANJE','AJUSTE')),
    CONSTRAINT CK_MOVPUNTOS_VALOR CHECK (PUNTOS <> 0)
);

