-- ============================================================
-- 11. TRIGGER PARA VALIDAR LOS COMPONENTES DE UN MENU
-- ============================================================

CREATE OR REPLACE TRIGGER TRG_VALIDAR_MENU_PRODUCTOS
BEFORE INSERT OR UPDATE ON MENU_COMPLETO
FOR EACH ROW
DECLARE
    V_SANDWICH PRODUCTO.TIPO_PRODUCTO%TYPE;
    V_BEBIDA PRODUCTO.TIPO_PRODUCTO%TYPE;
    V_ACOMP PRODUCTO.TIPO_PRODUCTO%TYPE;
BEGIN
    SELECT TIPO_PRODUCTO INTO V_SANDWICH
    FROM PRODUCTO WHERE ID_PRODUCTO=:NEW.ID_SANDWICH;

    SELECT TIPO_PRODUCTO INTO V_BEBIDA
    FROM PRODUCTO WHERE ID_PRODUCTO=:NEW.ID_BEBIDA;

    SELECT TIPO_PRODUCTO INTO V_ACOMP
    FROM PRODUCTO WHERE ID_PRODUCTO=:NEW.ID_ACOMPANAMIENTO;

    IF V_SANDWICH <> 'SANDWICH' THEN
        RAISE_APPLICATION_ERROR(-20001,
            'ID_SANDWICH debe corresponder a un sandwich.');
    END IF;

    IF V_BEBIDA <> 'BEBIDA' THEN
        RAISE_APPLICATION_ERROR(-20002,
            'ID_BEBIDA debe corresponder a una bebida.');
    END IF;

    IF V_ACOMP <> 'ACOMPANAMIENTO' THEN
        RAISE_APPLICATION_ERROR(-20003,
            'ID_ACOMPANAMIENTO debe corresponder a un acompanamiento.');
    END IF;
END;
/

